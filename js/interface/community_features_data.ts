// 每条功能给出：名称、工作区域、入口指引、功能说明、与原版 Blockbench 的差异（修改类）、
// 以及设置里对应的开关位置（有开关时）。
//
// 维护约定：
// - 新增功能后在这里补一条；area 只能取 COMMUNITY_FEATURE_AREAS 中的值。
// - entry 写「用户怎么点到」这一层（菜单路径 / 面板按钮 / 右键菜单）。
// - compare 只写与原版行为不同的部分；纯新增功能写「原版无此功能」。
// - toggle 写设置项路径（设置 → 社区版功能 → …）；没有开关就省略该字段。
// - 手册内容为中文（社区版面向中文用户，与软件内更新日志一致）。

export type CommunityFeatureArea =
	'编辑模式' | '绘画模式' | '动画模式' | 'UI界面' | '工具栏' | '设置' | '插件';

export const COMMUNITY_FEATURE_AREAS: CommunityFeatureArea[] = [
	'编辑模式', '绘画模式', '动画模式', 'UI界面', '工具栏', '设置', '插件',
];

export interface CommunityFeature {
	/** 唯一键，用于选中状态与搜索 */
	id: string;
	name: string;
	area: CommunityFeatureArea;
	/** 类型：新增功能 / 功能修改 */
	kind: '新增' | '修改';
	/** 入口指引：用户从哪里点进去 */
	entry: string;
	/** 功能说明：它做什么、用起来是什么样 */
	summary: string;
	/** 与原版 Blockbench 的差异（修改类必填） */
	compare?: string;
	/** 设置中的开关位置（省略表示无开关） */
	toggle?: string;
}

